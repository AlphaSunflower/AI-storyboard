T_H2 = find("1.1 项目背景")
T_H3 = find("1.3.1 技术创新点")
T_BODY = find("随着短视频")
T_CAP = find("图 1")

def new_para(template, text, style=None):
    el = copy.deepcopy(template._p)
    p = type(template)(el, template._parent)
    for r in list(p.runs[1:]):
        r._r.getparent().remove(r._r)
    if p.runs:
        p.runs[0].text = text
    else:
        p.add_run(text)
    if style:
        p.style = style
    return p

def new_fig(path, width=16.5):
    el = copy.deepcopy(T_BODY._p)
    p = type(T_BODY)(el, T_BODY._parent)
    for r in list(p.runs):
        r._r.getparent().remove(r._r)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(path, width=Cm(width))
    return p

def new_caption(text):
    p = new_para(T_CAP, text)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for r in p.runs:
        r.font.size = Pt(9)
        r.font.color.rgb = RGBColor(0x6b, 0x6b, 0x66)
    return p

def new_table(rows, header=True):
    t = d.add_table(rows=len(rows), cols=len(rows[0]))
    if d.tables[0].style is not None:
        t.style = d.tables[0].style
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = t.cell(ri, ci)
            cell.text = str(val)
            if header and ri == 0:
                for r in cell.paragraphs[0].runs:
                    r.font.bold = True
    return t

def insert_before(anchor_el, blocks):
    """按顺序将 blocks 插到 anchor 前。blocks: (kind, payload)"""
    for kind, payload in blocks:
        if kind == "h1":
            el = new_para(T_H1, payload)._p
        elif kind == "h2":
            el = new_para(T_H2, payload)._p
        elif kind == "h3":
            el = new_para(T_H3, payload)._p
        elif kind == "p":
            el = new_para(T_BODY, payload)._p
        elif kind == "b":
            el = new_para(T_BODY, payload)._p
        elif kind == "fig":
            el = new_fig(payload)._p
        elif kind == "cap":
            el = new_caption(payload)._p
        elif kind == "table":
            el = payload._tbl
        else:
            raise ValueError(kind)
        anchor_el._p.addprevious(el)

def insert_after(anchor_el, blocks):
    """按顺序将 blocks 插到 anchor 后（addnext 链）"""
    last = anchor_el._p
    for kind, payload in blocks:
        if kind == "h1":
            el = new_para(T_H1, payload)._p
        elif kind == "h2":
            el = new_para(T_H2, payload)._p
        elif kind == "h3":
            el = new_para(T_H3, payload)._p
        elif kind == "p":
            el = new_para(T_BODY, payload)._p
        elif kind == "b":
            el = new_para(T_BODY, payload)._p
        elif kind == "table":
            el = payload._tbl
        else:
            raise ValueError(kind)
        last.addnext(el)
        last = el

